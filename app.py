import streamlit as st
from calculator import calculate_probability

st.set_page_config(
    page_title="Калькулятор индивидуальной вероятности",
    page_icon="🫀",
    layout="centered",
)

st.title("Калькулятор индивидуальной вероятности")
st.caption(
    "Четырёхфакторная логистическая модель для оценки вероятности "
    "комбинированной конечной точки в течение 30 дней."
)

st.warning(
    "Инструмент предназначен только для исследовательского использования. "
    "Модель прошла внутреннюю оценку, но внешняя валидация не проводилась. "
    "Результат не предназначен для самостоятельного выбора лечения."
)

st.subheader("Исходные признаки")

# Hb вводится одним бинарным признаком: ниже порога исследования — Да, иначе — Нет.
low_hb = st.radio(
    "Снижение уровня гемоглобина ниже порога",
    options=["Нет", "Да"],
    horizontal=True,
    help="Выберите «Да», если гемоглобин ниже порога, использованного в исследовании.",
)

af = st.radio("Фибрилляция предсердий", ["Нет", "Да"], horizontal=True)
immobilization = st.radio(
    "Иммобилизация в течение предшествующих 4 недель",
    ["Нет", "Да"],
    horizontal=True,
)
tapse = st.radio("TAPSE <16 мм", ["Нет", "Да"], horizontal=True)

result = calculate_probability(
    low_hb=(low_hb == "Да"),
    atrial_fibrillation=(af == "Да"),
    immobilization_4_weeks=(immobilization == "Да"),
    tapse_below_16=(tapse == "Да"),
)

st.divider()
st.subheader("Результат")
st.metric(
    "Прогнозируемая вероятность комбинированной конечной точки за 30 дней",
    f"{result['probability_percent']:.1f}%".replace(".", ","),
)
st.caption(f"Линейный предиктор z = {result['z']:.3f}".replace(".", ","))
st.info(
    "Результат — индивидуальная прогнозируемая вероятность комбинированной "
    "конечной точки в течение 30 дней. Это не бинарный ответ «событие будет / "
    "не будет» и не оценка летальности отдельно."
)

with st.expander("Уравнение модели"):
    st.latex(r"z=-2.991+1.604X_1+1.392X_2+1.219X_3+1.228X_4")
    st.latex(r"P=\frac{1}{1+e^{-z}}")
    st.markdown(
        "- **X₁:** снижение уровня гемоглобина ниже порога (0 — нет, 1 — да).\n"
        "- **X₂:** фибрилляция предсердий (0 — нет, 1 — да).\n"
        "- **X₃:** иммобилизация в течение предшествующих 4 недель (0 — нет, 1 — да).\n"
        "- **X₄:** TAPSE <16 мм (0 — нет, 1 — да)."
    )

with st.expander("Исследовательские пороговые значения"):
    st.write(
        "Пороги рассчитаны на внутренней выборке из 241 пациента и не являются "
        "валидированными клиническими границами."
    )
    st.table([
        {"Порог": "8%", "Чувствительность": "93,8%", "Специфичность": "40,4%", "PPV": "28,1%", "NPV": "96,3%"},
        {"Порог": "38,25% (индекс Юдена)", "Чувствительность": "52,1%", "Специфичность": "88,1%", "PPV": "52,1%", "NPV": "88,1%"},
    ])
    st.caption(
        "Порог 8% приведён для дополнительного сравнения, а не как оптимальный "
        "порог модели. Порог 38,25% получен по индексу Юдена на внутренней выборке. "
        "Оба значения требуют внешней проверки и не присваиваются автоматически "
        "индивидуальному результату."
    )

with st.expander("Характеристики модели"):
    st.markdown(
        "- Разработка: 241 пациент, 48 событий.\n"
        "- Внутренняя OOB AUC: около 0,696.\n"
        "- Brier score OOB: около 0,131.\n"
        "- Внешняя валидация не проводилась."
    )

st.caption(
    "Модель разработана для пациентов со стабильной гемодинамикой и "
    "промежуточно-высоким или промежуточно-низким риском ТЭЛА. "
    "Применимость к другим группам не установлена."
)
st.caption(
    "Калькулятор не запрашивает ФИО, идентификаторы или медицинские записи "
    "и не сохраняет введённые значения пациента."
)
